import assert from 'node:assert/strict';
import { mkdtempSync, readFileSync, readdirSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { SessionManager } from '@earendil-works/pi-coding-agent';
import { collectionTools, currentCollectionPlan } from '../desktop/collection-plan.mjs';
import { buildCollectionData, currentCollectionData, saveCollectionFile, serializeCollectionData } from '../desktop/collection-data.mjs';
const manager = SessionManager.inMemory();
const plan = {goal:'当前页订单',capture:'current-page-table',source:{basis:'description',url:'https://example.com/orders'},fields:[{name:'订单号',meaning:'当前表头'},{name:'金额',meaning:'原文'}],samples:[['A-1','10']],missing:[],scope:'仅当前页，不翻页不自动筛选',maxRecords:10,delivery:{format:'data',reason:'一次性取得当前表格'}};
let snapshot = {pageUrl:plan.source.url, tablesTruncated:false, tables:[{headers:['金额','订单号'],rows:[['10','A-1'],['20','A-2']],issue:''}]};
let calls = 0, pause;
const tools = collectionTools({name:'storm_browser_page', execute:async()=>{calls++; if (pause) await pause; return {details:snapshot};}},()=>manager);
const ctx = {hasUI:true,ui:{confirm:async()=>true}};
await assert.rejects(tools[2].execute('run',{},undefined,undefined,ctx),/先确认/); assert.equal(calls,0);
await tools[1].execute('plan',{action:'propose',plan},undefined,undefined,ctx);
await tools[2].execute('run',{},undefined,undefined,ctx);
const record = currentCollectionPlan(manager), artifact = currentCollectionData(manager,record);
await tools[1].execute('same-plan',{action:'propose',plan},undefined,undefined,ctx);
assert.equal(currentCollectionData(manager,currentCollectionPlan(manager)),null,'Even reconfirming the same plan requires a fresh run');
await tools[2].execute('fresh-run',{},undefined,undefined,ctx);
assert.deepEqual(artifact.data.records,[['A-1','10'],['A-2','20']]);
assert.equal(artifact.data.allPagesVerified,false); assert.equal(artifact.data.filtersVerified,false);
assert.equal(JSON.parse(serializeCollectionData(artifact,'json')).digest,artifact.digest);
for (const bad of [{...snapshot,pageUrl:'https://example.com/different'}, {...snapshot,tablesTruncated:true}, {...snapshot,tables:[...snapshot.tables,...snapshot.tables]}, {...snapshot,tables:[{headers:['金额'],rows:[['10']],issue:''}]}, {...snapshot,tables:[{...snapshot.tables[0],issue:'unsupported'}]}, {...snapshot,tables:[{...snapshot.tables[0],rows:[['10','A-1'],['10','A-1']]}]}, {...snapshot,tables:[{...snapshot.tables[0],rows:[['99','wrong']]}]}, {...snapshot,tables:[{...snapshot.tables[0],rows:[['[REDACTED]','A-1']]}]}]) assert.throws(()=>buildCollectionData(record,bad));
assert.throws(()=>buildCollectionData({...record,plan:{...record.plan,maxRecords:1}},snapshot),/超限/);
snapshot = {...snapshot,tablesTruncated:true};
await assert.rejects(tools[2].execute('bad-run',{},undefined,undefined,ctx));
assert.equal(currentCollectionData(manager,record),null,'Failed rerun must invalidate an older ready artifact');
let release;
pause = new Promise(resolve=>{release=resolve;});
const abort = new AbortController();
const stopped = tools[2].execute('stopped',{},abort.signal,undefined,ctx);
await assert.rejects(tools[1].execute('parallel',{action:'current'},undefined,undefined,ctx),/等待结束/);
abort.abort(); release(); await assert.rejects(stopped); pause = undefined;
assert.equal(currentCollectionData(manager,record),null,'Stopped run never restores a prior artifact');
const formulaPlan = {...record,plan:{...plan,fields:[{name:'值',meaning:'原文'}],samples:[['=1+1']]}};
const formulas = buildCollectionData(formulaPlan,{pageUrl:plan.source.url,tables:[{headers:['值'],rows:[['=1+1'],['-2'],['a,"b'],['\t@x']],issue:''}]});
const csv = serializeCollectionData(formulas,'csv');
assert.match(csv,/"'=1\+1"/);assert.match(csv,/"'-2"/);assert.match(csv,/"a,""b"/);assert.match(csv,/"'\t@x"/);
assert.equal(JSON.parse(serializeCollectionData(formulas,'json')).records[0][0],'=1+1');
const temporary = mkdtempSync(join(tmpdir(),'storm-data-export-'));
try {
  const file = join(temporary,'result.csv'); saveCollectionFile(file,csv);
  assert.equal(readFileSync(file,'utf8'),csv); assert.throws(()=>saveCollectionFile(file,'overwrite'));
  assert.equal(readFileSync(file,'utf8'),csv); assert.deepEqual(readdirSync(temporary),['result.csv']);
} finally {rmSync(temporary,{recursive:true,force:true});}
manager.appendCustomEntry('mediastorm-collection-data', artifact);
await tools[1].execute('cancel-plan',{action:'propose',plan},undefined,undefined,{hasUI:true,ui:{confirm:async()=>false}});
assert.equal(currentCollectionData(manager,currentCollectionPlan(manager)),null);
console.log('PASS: exact current-table field/sample mapping, fail-closed limits/ambiguity, failed-run invalidation, JSON/CSV safety and exclusive atomic export.');
